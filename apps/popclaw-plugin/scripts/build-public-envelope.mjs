import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { mkdirSync, mkdtempSync, rmSync, copyFileSync, realpathSync, existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve, dirname, basename } from 'node:path';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
const bundle = resolve(root, '../../protocol');
// `--check` proves the artifact COMMITTED TO GIT is still what the pinned
// toolchain produces. It generates into a throwaway directory FIRST and only
// then byte-compares: writing over the checked-in file and diffing afterwards
// would compare the output against itself and pass on any staleness.
const check = process.argv.includes('--check');
const staging = check ? mkdtempSync(resolve(tmpdir(), 'public-envelope-check-')) : root;
// Registered before anything can throw: a failure anywhere below must not
// leave a 1 MB generated bundle behind in the system temp directory.
if (check) process.on('exit', () => rmSync(staging, { recursive: true, force: true }));
const artifact = resolve(root, 'src/protocol/public-envelope-generated.js');
// Hand-written, only COPIED below — never regenerated, so never counted as a
// verified-by-regeneration output. It is cross-checked against the module's
// real exports instead.
const declaration = resolve(root, 'src/protocol/public-envelope-generated.d.ts');
const generated = check ? resolve(staging, 'public-envelope-generated.js') : artifact;
// The generated module re-exports the whole algorithms index, but the .d.ts
// deliberately publishes a narrower surface: these lower-level sigil and
// house-session internals stay unreachable to plugin code. Pinning the
// narrowing by name is what makes the cross-check bite — a NEW export added by
// a later bundle is not on this list and fails.
const DECLARATION_OMITS = ['ACK_DOMAIN', 'REQUEST_DOMAIN', 'SIGIL_LEN', 'canonicalAckCore', 'canonicalRequestCore', 'crockford32Lower', 'normalizeSigilInput', 'sigil'];
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const digest = 'c530e69b51dcf8358b0e239b67d936dc9443ba7cad1f59b34b34520ad5e11337';
execFileSync('python3', [resolve(bundle, 'scripts/verify-bundle.py'), '--expected', digest], { stdio: 'inherit' });
const deps = createRequire(resolve(bundle, 'packages/contracts/ts/algorithms/package.json'));
function pinnedDependency(specifier) {
  const path = realpathSync(deps.resolve(specifier));
  if (!path.startsWith(`${resolve(bundle, 'node_modules')}/`))
    throw new Error('Run pnpm run setup:protocol; ambient protocol dependencies are not accepted');
  return path;
}
pinnedDependency('protobufjs/package.json');
if (deps('protobufjs/package.json').version !== '7.6.6') throw new Error('Run pnpm run setup:protocol to install the frozen public protocol toolchain');
const contracts = resolve(bundle, 'packages/contracts/ts/contracts/src');
const result = await build({
  absWorkingDir: root, metafile: true,
  stdin: { contents: `export { popclaw } from '@popclaw/contracts';\nexport * from '../../protocol/packages/contracts/ts/algorithms/src/index.ts';`,
    resolveDir: root, sourcefile: 'public-envelope-entry.ts', loader: 'ts' },
  outfile: generated,
  bundle: true, platform: 'node', format: 'esm', target: 'node22',
  // No version number in the banner: it was hand-written as ".5" and silently
  // outlived that bundle. The digest this was built from is verified above and
  // recorded in CONTENTS.json, which regenerates; a literal here cannot.
  banner: { js: '// Generated by scripts/build-public-envelope.mjs from the verified immutable protocol bundle.\nimport { createRequire as __createRequire } from "node:module"; const require = __createRequire(import.meta.url);' },
  alias: { '@popclaw/contracts/descriptor': resolve(contracts, 'generated/descriptor.js'),
    '@popclaw/contracts': resolve(contracts, 'index.ts'),
    'protobufjs/minimal.js': pinnedDependency('protobufjs/minimal.js'), 'protobufjs/minimal': pinnedDependency('protobufjs/minimal'), 'protobufjs': pinnedDependency('protobufjs'),
    '@noble/hashes/sha256': pinnedDependency('@noble/hashes/sha256') },
});

// tsc compiles with the repository root as rootDir (the pinned bundle under
// protocol/ sits outside this package), so compiled sources land under
// dist/apps/popclaw-plugin/ and reach the bundle at the same relative depth
// as the sources do.
const compiled = resolve(staging, 'dist/apps/popclaw-plugin/src/protocol');
mkdirSync(compiled, { recursive: true });
copyFileSync(generated, resolve(compiled, 'public-envelope-generated.js'));
copyFileSync(declaration, resolve(compiled, 'public-envelope-generated.d.ts'));
const declarations = resolve(staging, 'dist/protocol/packages/contracts/ts/contracts/src/generated');
mkdirSync(declarations, { recursive: true });
copyFileSync(resolve(contracts, 'generated/index.d.ts'), resolve(declarations, 'index.d.ts'));

// Keep the exact source notice and the actual bundled runtime dependency closure
// beside the distributable entry points. Do not depend on stripped comments.
const notices = resolve(staging, 'dist/bundled/public-envelope-notices');
mkdirSync(notices, { recursive: true });
for (const name of ['LICENSE', 'NOTICE']) copyFileSync(resolve(bundle, name), resolve(notices, name));
const runtimePackages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const path = resolve(root, input);
  if (!path.startsWith(`${resolve(bundle, 'node_modules')}/`)) continue;
  let directory = dirname(path);
  let metadata;
  for (;;) {
    const manifest = resolve(directory, 'package.json');
    if (existsSync(manifest)) {
      const candidate = JSON.parse(readFileSync(manifest, 'utf8'));
      if (typeof candidate.name === 'string' && typeof candidate.version === 'string') { metadata = candidate; break; }
    }
    const parent = dirname(directory);
    if (parent === directory) throw new Error('Bundled dependency package metadata missing');
    directory = parent;
  }
  const key = `${metadata.name}@${metadata.version}`;
  if (runtimePackages.has(key)) continue;
  const texts = readdirSync(directory).filter(name => /^(?:license|notice|copying)(?:[.-]|$)/i.test(name));
  if (!texts.some(name => /^license(?:[.-]|$)/i.test(name))) throw new Error(`Missing bundled license text: ${key}`);
  const destination = resolve(notices, 'runtime', key.replaceAll('/', '__'));
  mkdirSync(destination, { recursive: true });
  for (const name of texts) copyFileSync(resolve(directory, name), resolve(destination, basename(name)));
  runtimePackages.set(key, { name: metadata.name, version: metadata.version, license: metadata.license,
    texts: texts.map(name => `runtime/${key.replaceAll('/', '__')}/${name}`) });
}
writeFileSync(resolve(notices, 'CONTENTS.json'), JSON.stringify({ bundle_sha256: digest,
  scope: 'Pinned protocol source and runtime packages included in the generated JavaScript; excludes build-only dependencies.',
  runtime: [...runtimePackages.values()].sort((a, b) => a.name.localeCompare(b.name)) }, null, 2) + '\n');

// ---- --check: the committed artifact must BE the regenerated one ----
// Layered on top of, not instead of, the trusted-bundle digest verified above
// and the protocol-internal generated-source comparison. A digest-constant
// banner cannot satisfy this: the comparison is over every byte of the module.
if (check) {
  const fresh = readFileSync(generated);
  if (!existsSync(artifact))
    throw new Error(`STALE ARTIFACT: src/protocol/public-envelope-generated.js is missing. Run pnpm run build:protocol and commit the result.`);
  const committed = readFileSync(artifact);
  if (!committed.equals(fresh))
    throw new Error(`STALE ARTIFACT: src/protocol/public-envelope-generated.js is not what bundle ${digest} regenerates.\n` +
      `  committed:   ${committed.length} bytes sha256 ${sha256(committed)}\n` +
      `  regenerated: ${fresh.length} bytes sha256 ${sha256(fresh)}\n` +
      '  Run pnpm run build:protocol and commit the result.');

  // The .d.ts is hand-written and only copied, so "regenerated and verified"
  // never covers it. Verify what it actually claims instead: its declared
  // names and the module's real runtime exports must agree in BOTH
  // directions — a declared name the module lacks is a type-level lie, and
  // an export it omits hides new protocol surface from every consumer.
  const text = readFileSync(declaration, 'utf8');
  const declared = new Set();
  for (const [, name] of text.matchAll(/^export\s+declare\s+(?:const|function|class|let|var|type|interface|enum)\s+([A-Za-z_$][\w$]*)/gm)) declared.add(name);
  for (const [, list] of text.matchAll(/^export\s*\{([^}]*)\}/gm))
    for (const entry of list.split(',')) {
      const name = entry.trim().split(/\s+as\s+/).pop();
      if (name) declared.add(name);
    }
  if (declared.size === 0)
    throw new Error('DECLARATION UNREADABLE: no export declarations parsed out of src/protocol/public-envelope-generated.d.ts; the cross-check would have passed vacuously.');
  // Import the committed file, which the byte comparison above has already
  // proven identical to the regenerated one.
  const exported = new Set(Object.keys(await import(pathToFileURL(artifact).href)));
  if (exported.size === 0)
    throw new Error('ARTIFACT EXPORTS NOTHING: src/protocol/public-envelope-generated.js has no runtime exports.');
  const missing = [...declared].filter(name => !exported.has(name));
  if (missing.length)
    throw new Error(`DECLARATION AHEAD OF ARTIFACT: public-envelope-generated.d.ts declares ${missing.join(', ')}, which the module does not export.`);
  const undeclared = [...exported].filter(name => !declared.has(name) && !DECLARATION_OMITS.includes(name));
  if (undeclared.length)
    throw new Error(`DECLARATION BEHIND ARTIFACT: public-envelope-generated.js exports ${undeclared.join(', ')}, which the .d.ts neither declares nor pins as a deliberate omission.`);
  const stale = DECLARATION_OMITS.filter(name => !exported.has(name));
  if (stale.length)
    throw new Error(`OMISSION LIST STALE: ${stale.join(', ')} is pinned as deliberately undeclared but the module no longer exports it.`);

  // Say exactly what was regenerated and what was only cross-checked. The
  // .d.ts is never regenerated, so it is never part of the first count.
  process.stdout.write(`public-envelope --check OK: 1 regenerated output, byte-identical to the committed one ` +
    `(src/protocol/public-envelope-generated.js, ${committed.length} bytes, sha256 ${sha256(committed)}). ` +
    `0 regenerated declarations; 1 copied declaration cross-checked against the module it describes ` +
    `(src/protocol/public-envelope-generated.d.ts: ${declared.size} declared + ${DECLARATION_OMITS.length} pinned omissions === ${exported.size} runtime exports). ` +
    `Bundle ${digest}.\n`);
}
